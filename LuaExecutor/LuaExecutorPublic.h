#pragma once

typedef struct _LUA_EXEC_REQUEST {
	ULONG Tid;
	ULONG BytecodeLength;
	CHAR Bytecode[1];
} LUA_EXEC_REQUEST, *PLUA_EXEC_REQUEST;

#define LUA_EXEC_REQUEST_HEADER_SIZE		FIELD_OFFSET(LUA_EXEC_REQUEST, Bytecode)
#define LUA_EXEC_REQUEST_MAX_DATA_LENGTH	(1 << 20)		// 1 meg

#define EXEC_DEVICE							0x8003
#define IOCTL_WRITE_EXEC_REQUEST \
	CTL_CODE(EXEC_DEVICE, 0x800, METHOD_IN_DIRECT, FILE_ANY_ACCESS)
